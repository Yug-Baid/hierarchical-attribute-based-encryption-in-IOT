"""
Train the HABE eligibility Random Forest classifier.

Inputs:  training_data.csv (generated by generate_data.py)
Outputs: model.joblib       (serialized RandomForestClassifier)
         label_encoder.joblib (not needed here — labels are already int)

Evaluation output is written to stdout; redirect to train.log if desired.
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, confusion_matrix,
    classification_report,
)
from sklearn.model_selection import StratifiedKFold, cross_validate
import joblib

SEED = 42
MODEL_DIR = Path(__file__).parent

FEATURES = [
    "role_encoded",
    "location_match",
    "time_hour",
    "is_business_hours",
    "device_trust_encoded",
    "past_violations",
    "attr_sensitivity",
    "hierarchy_depth",
]
TARGET = "eligible"


def load_data() -> tuple[np.ndarray, np.ndarray]:
    csv = MODEL_DIR / "training_data.csv"
    if not csv.exists():
        raise FileNotFoundError(f"training_data.csv not found — run generate_data.py first")
    df = pd.read_csv(csv)
    X = df[FEATURES].values.astype(np.float32)
    y = df[TARGET].values.astype(int)
    return X, y


def train(X: np.ndarray, y: np.ndarray) -> RandomForestClassifier:
    # Hyperparameters tuned for the lightweight constraint:
    # - n_estimators=100: standard; diminishing returns beyond this for tabular data
    # - max_depth=12: prevents overfitting on the synthetic labels
    # - min_samples_leaf=4: stabilizes leaf predictions on noisy labels
    # - class_weight="balanced": handles moderate class imbalance
    # - n_jobs=-1: parallel tree building, irrelevant at inference time (single tree path)
    clf = RandomForestClassifier(
        n_estimators=100,
        max_depth=12,
        min_samples_leaf=4,
        class_weight="balanced",
        random_state=SEED,
        n_jobs=-1,
    )

    # 5-fold stratified CV for unbiased performance estimate
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
    cv_results = cross_validate(
        clf, X, y, cv=cv,
        scoring=["accuracy", "precision", "recall", "f1"],
        return_train_score=False,
    )

    print("=== 5-Fold Cross-Validation ===")
    for metric in ["accuracy", "precision", "recall", "f1"]:
        scores = cv_results[f"test_{metric}"]
        print(f"  {metric:12s}: {scores.mean():.4f} ± {scores.std():.4f}")

    # Final fit on full dataset
    clf.fit(X, y)

    # Held-out evaluation: stratified 80/20 split (consistent with ML paper §5.1)
    from sklearn.model_selection import train_test_split
    X_tr, X_te, y_tr, y_te = train_test_split(
        X, y, test_size=0.20, stratify=y, random_state=SEED
    )
    clf_eval = RandomForestClassifier(
        n_estimators=100, max_depth=12, min_samples_leaf=4,
        class_weight="balanced", random_state=SEED, n_jobs=-1,
    )
    clf_eval.fit(X_tr, y_tr)
    y_pred = clf_eval.predict(X_te)

    print("\n=== Held-out Test Set (20%) ===")
    print(f"  Accuracy  : {accuracy_score(y_te, y_pred):.4f}")
    print(f"  Precision : {precision_score(y_te, y_pred):.4f}")
    print(f"  Recall    : {recall_score(y_te, y_pred):.4f}")
    print(f"  F1        : {f1_score(y_te, y_pred):.4f}")
    print(f"  MCC       : {matthews_corrcoef(y_te, y_pred):.4f}")

    cm = confusion_matrix(y_te, y_pred)
    print(f"\n  Confusion matrix (TN FP / FN TP):")
    print(f"    [{cm[0,0]:4d}  {cm[0,1]:4d}]")
    print(f"    [{cm[1,0]:4d}  {cm[1,1]:4d}]")

    print("\n  Classification report:")
    print(classification_report(y_te, y_pred, target_names=["ineligible", "eligible"]))

    # Feature importance
    print("=== Feature Importances (full-data model) ===")
    importances = sorted(
        zip(FEATURES, clf.feature_importances_),
        key=lambda x: -x[1]
    )
    for feat, imp in importances:
        print(f"  {feat:25s}: {imp:.4f}")

    return clf


def save(clf: RandomForestClassifier) -> None:
    out = MODEL_DIR / "model.joblib"
    meta = MODEL_DIR / "model_meta.json"

    joblib.dump(clf, out)
    with open(meta, "w") as f:
        json.dump({"features": FEATURES, "target": TARGET, "n_estimators": clf.n_estimators}, f, indent=2)

    print(f"\nModel saved → {out}")
    print(f"Meta  saved → {meta}")


if __name__ == "__main__":
    X, y = load_data()
    print(f"Loaded {len(X)} samples, {X.shape[1]} features")
    print(f"Class distribution: eligible={y.sum()} ({y.mean():.1%}), ineligible={len(y)-y.sum()}\n")

    clf = train(X, y)
    save(clf)